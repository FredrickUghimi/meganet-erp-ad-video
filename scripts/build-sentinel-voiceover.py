"""Assemble public/voiceover-sentinel.mp3 and src/sentinelTimings.ts.

Input: <work>/line{1..5}.mp3 + line{1..5}.json, made with edge-tts (voice en-NG-AbeoNeural,
boundary=WordBoundary). The voice leaves ~0.9 s of silence after every sentence; those
long gaps are cut down to GAPS below. No word is trimmed, sped up or altered.
Usage: python3 build-sentinel-voiceover.py <work_dir> <repo_dir>
"""
import array, json, subprocess, sys

work, repo = sys.argv[1], sys.argv[2]
SR = 44100
TOTAL = 20.7  # video length in seconds (voice ends ~20.15 s; last frame holds ~0.5 s after)

# Script tokens (display text incl. punctuation), one list per narration line.
TOKENS = [
    "Tests done. Drugs dispensed. Billed? Or lost?".split(),
    "Meet Financial Sentinel, in Mega-Net EHR Cloud.".split(),
    "One click checks clinical records against bills and flags unbilled services, duplicates and rejected claim patterns.".split(),
    "Each finding is ranked and explained. Your team decides.".split(),
    "Book a free demo. Message us on WhatsApp.".split(),
]
# Per line: word-index ranges kept as one continuous clip, and the gap (s) after each clip.
SEGS = [
    ([(0, 1), (2, 3), (4, 4), (5, 6)], [0.25, 0.25, 0.30]),
    ([(0, 6)], []),
    ([(0, 15)], []),
    ([(0, 5), (6, 8)], [0.35]),
    ([(0, 3), (4, 7)], [0.35]),
]
# Line 1 starts here; every later line starts LINE_GAP after the previous line ends (s).
FIRST_START = 0.15
LINE_GAP = 0.30


def decode(path, a, b):
    out = subprocess.run(
        ["ffmpeg", "-v", "error", "-ss", f"{a:.3f}", "-to", f"{b:.3f}", "-i", path,
         "-ac", "1", "-ar", str(SR), "-f", "s16le", "-"], capture_output=True, check=True).stdout
    s = array.array("h"); s.frombytes(out)
    n = int(0.008 * SR)  # 8 ms fades
    for i in range(min(n, len(s))):
        g = i / n; s[i] = int(s[i] * g); s[-1 - i] = int(s[-1 - i] * g)
    return s


master = array.array("h", [0] * int(TOTAL * SR))
words, lines = [], []
for li, (segs, gaps) in enumerate(SEGS):
    wj = json.load(open(f"{work}/line{li+1}.json"))
    assert len(wj) == len(TOKENS[li]), (li, len(wj), len(TOKENS[li]))
    t = lines[-1][1] + LINE_GAP if lines else FIRST_START
    start = t
    for si, (i0, i1) in enumerate(segs):
        a = wj[i0]["s"] - 0.03
        b = wj[i1]["s"] + wj[i1]["d"] + 0.06
        clip = decode(f"{work}/line{li+1}.mp3", a, b)
        p = int(round(t * SR))
        master[p:p + len(clip)] = clip
        for k in range(i0, i1 + 1):
            ws = t + (wj[k]["s"] - a)
            words.append({"w": TOKENS[li][k], "s": round(ws, 3), "e": round(ws + wj[k]["d"], 3), "line": li + 1})
        t += len(clip) / SR + (gaps[si] if si < len(gaps) else 0)
    lines.append((start, t))

open(f"{work}/master.raw", "wb").write(master.tobytes())
subprocess.run(["ffmpeg", "-v", "error", "-y", "-f", "s16le", "-ar", str(SR), "-ac", "1", "-i", f"{work}/master.raw",
                "-af", "loudnorm=I=-16.5:TP=-2:LRA=7,volume=3.5dB,alimiter=limit=0.9",
                "-ar", str(SR), "-ac", "1", "-b:a", "128k", f"{repo}/public/voiceover-sentinel.mp3"], check=True)

ts = ["// Generated by scripts/build-sentinel-voiceover.py - word timings (seconds) of public/voiceover-sentinel.mp3.",
      "export type TimedWord = {w: string; s: number; e: number; line: number};",
      "export const WORDS: TimedWord[] = " + json.dumps(words, indent=1) + ";",
      "export const VOICE_END = %.3f;" % lines[-1][1]]
open(f"{repo}/src/sentinelTimings.ts", "w").write("\n".join(ts) + "\n")
for (a, b) in lines: print(f"line {a:.2f}-{b:.2f}")
print("words", len(words))
