"""Generates the MegaNetPharmacyInteractionAd voiceover (v4: 7-sentence feature-spotlight script, target 28-30s): one edge-tts call per sentence
(en-NG-EzinneNeural, word-level boundaries), leading/trailing silence of each
sentence trimmed, sentences joined with 0.3s gaps, words never sped up.
Word timings are written to src/pharmacyTimings.ts and the audio to
public/voiceover-pharmacy.mp3.

edge-tts builds its SSL context from certifi, which ignores SSL_CERT_FILE, so
certifi is pointed at the proxy CA bundle here. Verification stays ON.

usage: python3 -I scripts/pharmacy_voice.py <scratch-dir>"""
import asyncio, json, subprocess, sys, pathlib, certifi

CA = "/root/.ccr/ca-bundle.crt"
certifi.where = lambda: CA  # must happen before edge_tts builds its SSL context
import edge_tts  # noqa: E402

VOICE = "en-NG-EzinneNeural"
GAP = 0.3
# One entry per scene; each scene is one or more sentences, spoken with a 0.3s gap.
SCENES = [
    ["A doctor is about to prescribe two drugs for one patient.", "Some drug pairs can interact."],
    ["Mega-Net EHR Cloud has a feature for that: a drug interaction warning."],
    ["When the doctor tries to save the prescription, a warning appears if the two drugs are a defined interaction pair."],
    ["For a severe interaction, the doctor must stop and type CONFIRM to continue.", "Nothing is saved until they do."],
    ["Mega-Net EHR Cloud. Book a free demo. Message us on WhatsApp."],
]
root = pathlib.Path(__file__).resolve().parent.parent
work = pathlib.Path(sys.argv[1]); work.mkdir(parents=True, exist_ok=True)


async def synth(name, text):
    comm = edge_tts.Communicate(text, VOICE, boundary="WordBoundary")
    words, audio = [], bytearray()
    async for ch in comm.stream():
        if ch["type"] == "audio":
            audio += ch["data"]
        elif ch["type"] == "WordBoundary":
            words.append({"text": ch["text"], "start": ch["offset"] / 1e7, "dur": ch["duration"] / 1e7})
    (work / f"{name}.mp3").write_bytes(audio)
    return words


def dur(p):
    return float(subprocess.check_output(["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", str(p)]))


async def main():
    segs = []  # (scene index, text, words)
    for si, sentences in enumerate(SCENES):
        for ki, text in enumerate(sentences):
            segs.append((si, text, await synth(f"s{si}_{ki}", text)))
    t = 0.0
    inputs, filters = [], []
    scenes_out = [{"text": " ".join(s), "start": None, "end": None, "words": []} for s in SCENES]
    for n, (si, text, words) in enumerate(segs):
        src = work / f"s{si}_{sum(1 for x in segs[:n] if x[0] == si)}.mp3"
        total = dur(src)
        lead = max(words[0]["start"] - 0.03, 0)
        end = min(words[-1]["start"] + words[-1]["dur"] + 0.06, total)
        inputs += ["-i", str(src)]
        filters.append(f"[{n}:a]atrim=start={lead:.4f}:end={end:.4f},asetpts=PTS-STARTPTS,apad=pad_dur={GAP}[a{n}]")
        sc = scenes_out[si]
        if sc["start"] is None:
            sc["start"] = t
        sc["end"] = t + (end - lead)
        sc["words"] += [{"text": w["text"], "start": t + w["start"] - lead, "end": t + w["start"] + w["dur"] - lead} for w in words]
        t += (end - lead) + GAP
    n = len(segs)
    fc = ";".join(filters) + ";" + "".join(f"[a{i}]" for i in range(n)) + f"concat=n={n}:v=0:a=1[out]"
    out = root / "public" / "voiceover-pharmacy.mp3"
    subprocess.check_call(["ffmpeg", "-y", "-loglevel", "error", *inputs, "-filter_complex", fc, "-map", "[out]",
                           "-ar", "24000", "-b:a", "96k", str(out)])
    voice_end = scenes_out[-1]["end"]
    (root / "src" / "pharmacyTimings.ts").write_text(
        "// Generated by scripts/pharmacy_voice.py - do not edit.\n// Seconds from the start of voiceover-pharmacy.mp3.\n"
        "export const VOICE_END = %r;\n"
        "export const LINES: {text: string; start: number; end: number; words: {text: string; start: number; end: number}[]}[] = %s;\n"
        % (voice_end, json.dumps(scenes_out, indent=1)))
    print("voice ends", round(voice_end, 3), "file", round(dur(out), 3))
    for sc in scenes_out:
        print(round(sc["start"], 2), round(sc["end"], 2), [w["text"] for w in sc["words"]])

asyncio.run(main())
