"""Generates the MegaNetAssistantAd voiceover: one edge-tts call per line
(en-NG-AbeoNeural, word-level boundaries), then joins the lines with 0.3s
gaps. Word timings are written to src/assistantTimings.ts.

edge-tts builds its SSL context from certifi, which ignores SSL_CERT_FILE, so
certifi is pointed at the proxy CA bundle here. Verification stays ON."""
import asyncio, json, subprocess, sys, pathlib, certifi

CA = "/root/.ccr/ca-bundle.crt"
certifi.where = lambda: CA  # must happen before edge_tts builds its SSL context
import edge_tts  # noqa: E402

VOICE = "en-NG-AbeoNeural"
GAP = 0.3
LINES = [
    "Just ask your business.",
    "Who owes you the most?",
    "Which products are running low?",
    "What did you spend this month?",
    "How is your profit this month?",
    "Answers from your own data, only for those allowed to see them.",
    "Book a free demo with Mega-Net.",
]
root = pathlib.Path(__file__).resolve().parent.parent
work = pathlib.Path(sys.argv[1]); work.mkdir(parents=True, exist_ok=True)


async def synth(i, text):
    comm = edge_tts.Communicate(text, VOICE, boundary="WordBoundary")
    words, audio = [], bytearray()
    async for ch in comm.stream():
        if ch["type"] == "audio":
            audio += ch["data"]
        elif ch["type"] == "WordBoundary":
            words.append({"text": ch["text"], "start": ch["offset"] / 1e7, "dur": ch["duration"] / 1e7})
    (work / f"line{i}.mp3").write_bytes(audio)
    return words


def dur(p):
    return float(subprocess.check_output(["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", str(p)]))


async def main():
    all_words = [await synth(i, t) for i, t in enumerate(LINES)]
    # trim leading/trailing silence of each line, keeping the words untouched
    t = 0.0
    inputs, filters, lines_out = [], [], []
    for i, words in enumerate(all_words):
        src = work / f"line{i}.mp3"
        total = dur(src)
        lead = max(words[0]["start"] - 0.03, 0)
        end = min(words[-1]["start"] + words[-1]["dur"] + 0.06, total)
        inputs += ["-i", str(src)]
        filters.append(f"[{i}:a]atrim=start={lead:.4f}:end={end:.4f},asetpts=PTS-STARTPTS,apad=pad_dur={GAP}[a{i}]")
        # padding is added after trim: line length = (end-lead) + GAP, but the gap is applied after each line
        lines_out.append({
            "text": LINES[i],
            "start": t,
            "end": t + (end - lead),
            "words": [{"text": w["text"], "start": t + w["start"] - lead, "end": t + w["start"] + w["dur"] - lead} for w in words],
        })
        t += (end - lead) + GAP
    n = len(LINES)
    fc = ";".join(filters) + ";" + "".join(f"[a{i}]" for i in range(n)) + f"concat=n={n}:v=0:a=1[out]"
    out = root / "public" / "voiceover-assistant.mp3"
    subprocess.check_call(["ffmpeg", "-y", "-loglevel", "error", *inputs, "-filter_complex", fc, "-map", "[out]",
                           "-ar", "24000", "-b:a", "96k", str(out)])
    voice_end = lines_out[-1]["end"]
    (root / "src" / "assistantTimings.ts").write_text("// Generated by scripts/assistant_voice.py - do not edit.\n// Seconds from the start of voiceover-assistant.mp3.\nexport const VOICE_END = %r;\nexport const LINES: {text: string; start: number; end: number; words: {text: string; start: number; end: number}[]}[] = %s;\n" % (voice_end, json.dumps(lines_out, indent=1)))
    print("voice ends", round(voice_end, 3), "file", round(dur(out), 3))

asyncio.run(main())
